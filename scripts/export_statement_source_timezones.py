"""Freeze existing Shanghai/Hong Kong ZoneRules and independent atZone boundary vectors."""
import argparse
import json
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "compose/business-domain/src/commonMain/kotlin/com/finance/tracker/business/domain/StatementSourceZoneData.kt"
VECTORS = ROOT / "compose/business-domain/src/commonTest/kotlin/com/finance/tracker/business/domain/StatementSourceZoneOriginalVectors.kt"
JAVA = r'''
import java.time.*;
import java.time.format.*;
import java.time.zone.*;
import java.util.*;
public class StatementZoneOracle {
 static final DateTimeFormatter SECONDS=DateTimeFormatter.ofPattern("uuuu-MM-dd'T'HH:mm:ss", Locale.ROOT);
 static String text(LocalDateTime value) {
  return SECONDS.format(value)+(value.getNano()==0?"":"."+String.format(Locale.ROOT,"%06d",value.getNano()/1000));
 }
 public static void main(String[] args) {
  for(String id:new String[]{"Asia/Shanghai","Asia/Hong_Kong"}) {
   var zone=ZoneId.of(id);var rules=zone.getRules();var transitions=rules.getTransitions();
   if(transitions.isEmpty() || !rules.getTransitionRules().isEmpty()) throw new IllegalStateException("Review recurring source zone rules");
   System.err.println(id+" tzdb="+ZoneRulesProvider.getVersions(id).lastKey());
   System.out.println("zone\t"+id+"\t"+transitions.getFirst().getOffsetBefore().getTotalSeconds());
   var samples=new LinkedHashSet<LocalDateTime>();
   for(var t:transitions) {
    System.out.println("transition\t"+id+"\t"+t.toEpochSecond()+"\t"+t.getOffsetBefore().getTotalSeconds()+"\t"+t.getOffsetAfter().getTotalSeconds());
    for(var boundary:new LocalDateTime[]{t.getDateTimeBefore(),t.getDateTimeAfter()})
     for(int delta:new int[]{-86400,-7200,-3600,-1,0,1,1800,3599,3600,7200,86400}) {
      samples.add(boundary.plusSeconds(delta));samples.add(boundary.plusSeconds(delta).withNano(123456000));
     }
   }
   for(int year:new int[]{1,2,99,999,1800,1900,1970,2000,2026,9998,9999})
    for(int month:new int[]{1,6,12}) samples.add(LocalDateTime.of(year,month,1,0,0,0));
   var random=new Random(0x51a7eL);
   for(int n=0;n<512;n++) samples.add(LocalDateTime.of(1+random.nextInt(9999),1+random.nextInt(12),
    1+random.nextInt(28),random.nextInt(24),random.nextInt(60),random.nextInt(60),random.nextInt(1000000)*1000));
   for(var local:samples) {
    var utc=LocalDateTime.ofInstant(local.atZone(zone).toInstant(),ZoneOffset.UTC);
    System.out.println("vector\t"+id+"\t"+text(local)+"\t"+text(utc)+"+00:00");
   }
  }
 }
}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="ft-source-zones-") as directory:
        source = Path(directory) / "StatementZoneOracle.java"
        source.write_text(JAVA)
        lines = subprocess.run(["java", str(source)], check=True, text=True, capture_output=True)
    print(lines.stderr, end="")
    zones, rows = {}, []
    for line in lines.stdout.splitlines():
        kind, zone, *values = line.split("\t")
        if kind == "zone":
            zones[zone] = {"initial": int(values[0]), "transitions": []}
        elif kind == "transition":
            zones[zone]["transitions"].append(tuple(map(int, values)))
        elif kind == "vector":
            rows.append(["icbc_asia" if zone == "Asia/Hong_Kong" else "wechat", *values])
        else:
            raise RuntimeError(kind)
    assert set(zones) == {"Asia/Shanghai", "Asia/Hong_Kong"}
    content = '''package com.finance.tracker.business.domain

// Generated by scripts/export_statement_source_timezones.py from the existing JVM source zones.
// Arrays stay private; this is the source contract's finite history, not a general timezone API.
internal object StatementSourceZoneData {
'''
    for name, zone in (("shanghai", "Asia/Shanghai"), ("hongKong", "Asia/Hong_Kong")):
        item = zones[zone]
        content += f"    private const val {name}Initial = {item['initial']}\n"
        content += f"    private val {name} = longArrayOf(\n"
        content += "\n".join("        " + ", ".join(str(v) + "L" for v in t) + "," for t in item["transitions"])
        content += "\n    )\n"
    content += '''
    fun offsetSeconds(source: String, localSecond: Long): Int {
        val (initial, transitions) = when (source) {
            "alipay", "wechat", "icbc_credit", "icbc_debit", "ccb_debit" -> shanghaiInitial to shanghai
            "icbc_asia" -> hongKongInitial to hongKong
            else -> return 0
        }
        var offset = initial
        for (index in transitions.indices step 3) {
            val instant = transitions[index]
            val before = transitions[index + 1].toInt()
            val after = transitions[index + 2].toInt()
            // atZone shifts a gap forward and chooses the earlier offset in an overlap.
            if (localSecond < instant + maxOf(before, after)) return before
            offset = after
        }
        return offset
    }
}
'''
    payload = json.dumps(rows, ensure_ascii=True, separators=(",", ":"))
    chunks = [json.dumps(payload[i:i + 3000], ensure_ascii=True).replace('$', r'\$') for i in range(0, len(payload), 3000)]
    vectors = ("package com.finance.tracker.business.domain\n\n"
        "// Generated by scripts/export_statement_source_timezones.py using JVM LocalDateTime.atZone.\n"
        "internal object StatementSourceZoneOriginalVectors {\n"
        "    val json: String by lazy { listOf(\n" + ",\n".join("        " + c for c in chunks) + "\n    ).joinToString(\"\") }\n}\n")
    for target, expected in ((TARGET, content), (VECTORS, vectors)):
        if args.check:
            if not target.exists() or target.read_text() != expected:
                raise RuntimeError(f"Source-zone artifact is stale: {target.relative_to(ROOT)}")
        else:
            target.write_text(expected)
    print(f"{sum(len(z['transitions']) for z in zones.values())} transitions, {len(rows)} independent atZone samples")


if __name__ == "__main__":
    main()
