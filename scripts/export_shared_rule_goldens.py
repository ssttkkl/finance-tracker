"""Generate deterministic, anonymous KMP rule fixtures from the current Python domain.

Run with the project's Python 3.11 interpreter. --check verifies both generated
files without writing; no database, network, credentials or user bills are used.
"""
from __future__ import annotations

import argparse
from copy import deepcopy
from decimal import Decimal
import json
from pathlib import Path
import random
import unicodedata

from ft.domain.cash_record_policy import CashRecordPolicyError, validate_cash_component_consistency
from ft.domain.decimal import exact_decimal


ROOT = Path(__file__).resolve().parents[1]
DOMAIN = ROOT / "compose/business-domain/src"


def generated_files() -> dict[Path, str]:
    if unicodedata.unidata_version != "14.0.0":
        raise ValueError("use the baseline Python 3.11 / Unicode 14.0.0 oracle; do not silently change character semantics")
    digit_starts = [code for code in range(0x110000) if unicodedata.decimal(chr(code), None) == 0]
    whitespace = [code for code in range(0x110000) if chr(code).isspace()]
    character_data = """package com.finance.tracker.business.domain

// Generated by scripts/export_shared_rule_goldens.py from Python's Unicode 14.0.0 oracle.
// Verify with that script's --check option before changing the supported character set.
internal val decimalDigitStarts = intArrayOf(%s)
internal val decimalWhitespace = intArrayOf(%s)
""" % (", ".join(hex(code) for code in digit_starts), ", ".join(hex(code) for code in whitespace))
    amounts = ["0", "-0", "0E-19", "-0.0000", "1E+19", "1E-18", "-1E-18",
        "1.2345678901234567890", "99999999999999999999.999999999999999999",
        "-99999999999999999999.999999999999999999", "NaN", "sNaN", "Infinity", "-Infinity",
        "1E+20", "1E-19", "0E-20", "99999999999999999999.9999999999999999999",
        " .5 ", "1_000.00", "-١٢.٥٠", "１２.５０", "𝟙𝟚.𝟝𝟘", "\u001c1.25\u001f",
        "0e999999999999999999", "0e1000000000000000000", "", ".", "--1", "1,000", "1e", "_1_._0_",
        "_ 1_", "_1 _", " _ 1 _ ", "__1__", "1_e_2", "𝟘E-19",
        "0.0e1000000000000000000", "0.00e1000000000000000001", "0.0e1000000000000000001",
        "1e-9223372036854775808", "0e-9223372036854775808", "1e-9223372036854775807",
        "1.0e-9223372036854775808", "0e9223372036854775807", "1e9223372036854775807"]
    decimal_cases = []
    for text in amounts:
        try:
            exact_decimal(text)
            valid = True
        except ValueError:
            valid = False
        decimal_cases.append({"input": text, "valid": valid})
    base = {"amount": "-10.25", "currency": "CNY", "account_id": "a", "cash_granularity": "atomic",
            "components": [{"account_id": "a", "amount": "-10.25", "currency": "CNY", "ordinal": 0}]}
    records = [{}, deepcopy(base)]
    for field in ("amount", "currency", "account_id", "cash_granularity", "components"):
        for value in (True, False, 1.0, -1, 0, 1, [], {}, ""):
            record = deepcopy(base); record[field] = value; records.append(record)
    for field in ("component_id", "account_id", "amount", "currency", "ordinal"):
        for value in (None, True, False, 1.0, -1, 0, 1, [], {}, "", "1"):
            record = deepcopy(base); record["components"][0][field] = value; records.append(record)
    for field, values in {"amount": [None, "", "NaN", "1e20", "1e-19", "0", "10.25"],
            "currency": [None, "", "cny", "CN", "USD"], "account_id": [None, "", "b"],
            "cash_granularity": [None, "", "aggregate", "unknown"], "components": [None, []]}.items():
        for value in values:
            record = deepcopy(base); record[field] = value; records.append(record)
    for field, values in {"amount": [None, "", "0", "10.25", "-1", "-1e-18"],
            "currency": [None, "", "USD"], "account_id": [None, "", "b"],
            "ordinal": [None, -1, 2147483648]}.items():
        for value in values:
            record = deepcopy(base); record["components"][0][field] = value; records.append(record)
    rng = random.Random(20261028)
    for _ in range(200):
        scale = rng.choice((0, 2, 6, 18))
        left, right = rng.randrange(0, 10**20), rng.randrange(0, 10**20)
        sign = rng.choice((-1, 1))
        def text(value):
            return format(Decimal(sign * value).scaleb(-scale), "f")
        record = {"amount": text(left + right), "currency": "CNY", "account_id": None,
            "cash_granularity": "aggregate", "components": [
                {"account_id": "a", "amount": text(left), "currency": "CNY", "ordinal": 0},
                {"account_id": "b", "amount": text(right), "currency": "CNY", "ordinal": 1}]}
        fault = rng.randrange(5)
        if fault == 1: record["components"][1]["ordinal"] = 0
        if fault == 2: record["components"][1]["currency"] = "USD"
        if fault == 3: record["components"][1]["amount"] = text(right + 1)
        if fault == 4: record["components"][1]["amount"] = None
        records.append(record)
    policy_cases = []
    for record in records:
        try:
            validate_cash_component_consistency(record)
            error = None
        except CashRecordPolicyError as failure:
            error = {"code": failure.code, "fields": list(failure.fields)}
        policy_cases.append({"record": record, "error": error})
    encoded = json.dumps({"decimals": decimal_cases, "components": policy_cases}, ensure_ascii=False, separators=(",", ":"))
    chunks = [encoded[index:index + 12000].replace("$", "${'$'}") for index in range(0, len(encoded), 12000)]
    fixtures = """package com.finance.tracker.business.domain

// Generated from ft.domain.decimal and ft.domain.cash_record_policy; verify with --check.
internal val sharedRuleGoldenJson = listOf(
%s
).joinToString("")
""" % ",\n".join('    """' + chunk + '"""' for chunk in chunks)
    return {
        DOMAIN / "commonMain/kotlin/com/finance/tracker/business/domain/DecimalCharacterData.kt": character_data,
        DOMAIN / "commonTest/kotlin/com/finance/tracker/business/domain/SharedRuleGoldenData.kt": fixtures,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    for path, content in generated_files().items():
        if arguments.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"generated content differs: {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print("shared rule oracle files verified" if arguments.check else "shared rule oracle files generated")


if __name__ == "__main__":
    main()
