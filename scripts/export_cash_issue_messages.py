"""Generate the existing safe cash issue catalog for the Kotlin backend."""
from __future__ import annotations
import argparse
import json
from pathlib import Path
from ft.application.cash_import_issues import _REASONS

ROOT=Path(__file__).resolve().parents[1]
TARGET=ROOT/'compose/backend/src/main/kotlin/com/finance/tracker/backend/CashIssueReasons.kt'


def content():
    def quoted(value):return json.dumps(value,ensure_ascii=False).replace('$','\\$')
    rows=['package com.finance.tracker.backend','','// Generated by scripts/export_cash_issue_messages.py; verified with --check.',
        'internal val cashIssueReasons=mapOf(']
    rows.extend(f'    {quoted(code)} to ({quoted(message)} to {quoted(action)}),' for code,(message,action) in _REASONS.items())
    return '\n'.join([*rows,')',''])


def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args();data=content()
    if args.check:
        if TARGET.read_text()!=data:raise RuntimeError('Cash issue catalog is stale')
    else:TARGET.write_text(data)
    print(f'{len(_REASONS)} cash issue reasons '+('verified' if args.check else 'generated'))


if __name__=='__main__':main()
