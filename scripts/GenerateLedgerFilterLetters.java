import java.util.ArrayList;

/** Emit the original currency-filter letter membership, with no timezone or case-mapping data. */
class GenerateLedgerFilterLetters {
    public static void main(String[] args) {
        if (!"21.0.6+7-LTS".equals(System.getProperty("java.runtime.version")) ||
            !"Eclipse Adoptium".equals(System.getProperty("java.vendor")))
            throw new IllegalStateException("Use Temurin 21.0.6+7-LTS; input membership changes require compatibility review");
        var ranges = new ArrayList<Integer>();
        int start = -1;
        for (int point = 0; point <= 0x10ffff; point++) {
            boolean letter = Character.isLetter(point);
            if (letter && start < 0) start = point;
            if (!letter && start >= 0) { ranges.add(start); ranges.add(point - 1); start = -1; }
        }
        if (start >= 0) throw new IllegalStateException("Expected final scalar not to be a letter");
        System.out.println("package com.finance.tracker.business.domain\n");
        System.out.println("// Generated by scripts/GenerateLedgerFilterLetters.java with Temurin 21.0.6+7-LTS.");
        System.out.println("// Original Character.isLetter membership used for the three-code-point currency filter.");
        System.out.println("internal object LedgerFilterCharacters {\n    private val letters = intArrayOf(");
        for (int index = 0; index < ranges.size(); index++) {
            if (index % 8 == 0) System.out.print("        ");
            System.out.print(ranges.get(index) + ",");
            if (index % 8 == 7 || index == ranges.size() - 1) System.out.println(); else System.out.print(" ");
        }
        System.out.println("    )\n    fun isLetter(point: Int): Boolean {\n        var first = 0\n        var last = letters.size / 2 - 1\n        while (first <= last) {\n            val middle = (first + last) ushr 1\n            when {\n                point < letters[middle * 2] -> last = middle - 1\n                point > letters[middle * 2 + 1] -> first = middle + 1\n                else -> return true\n            }\n        }\n        return false\n    }\n}");
    }
}
