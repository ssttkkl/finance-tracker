"""Freeze public Java character properties for the private merchant boundary model."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'compose/business-domain/src/commonMain/kotlin/com/finance/tracker/business/domain/MerchantCharacterData.kt'
JAVA = r'''
public class MerchantCharacterProperties {
    static int category(int cp) {
        return switch (Character.getType(cp)) {
            case Character.UPPERCASE_LETTER, Character.LOWERCASE_LETTER,
                 Character.TITLECASE_LETTER, Character.MODIFIER_LETTER,
                 Character.OTHER_LETTER, Character.COMBINING_SPACING_MARK -> 1;
            case Character.DECIMAL_DIGIT_NUMBER, Character.LETTER_NUMBER, Character.OTHER_NUMBER -> 2;
            case Character.NON_SPACING_MARK, Character.ENCLOSING_MARK -> 3;
            case Character.FORMAT -> 4;
            case Character.CONNECTOR_PUNCTUATION -> 5;
            default -> 0;
        };
    }
    static boolean cased(int cp) {
        int type = Character.getType(cp);
        return type == Character.UPPERCASE_LETTER || type == Character.LOWERCASE_LETTER
            || type == Character.TITLECASE_LETTER;
    }
    public static void main(String[] args) {
        if (!System.getProperty("java.runtime.version").equals("21.0.6+7-LTS")
            || !System.getProperty("java.vendor").equals("Eclipse Adoptium"))
            throw new IllegalStateException("Requires the frozen Temurin 21.0.6+7 baseline");
        for (int property = 1; property <= 6; property++) {
            int start = -1;
            for (int cp = 0; cp <= 0x110000; cp++) {
                boolean included = cp < 0x110000 && (property == 6 ? cased(cp) : category(cp) == property);
                if (included && start < 0) start = cp;
                if (!included && start >= 0) {
                    System.out.println(property + "\t" + start + "\t" + (cp - 1));
                    start = -1;
                }
            }
        }
    }
}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--java', default=str(Path(os.environ['JAVA_HOME']) / 'bin/java') if 'JAVA_HOME' in os.environ else 'java')
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix='ft-merchant-properties-') as directory:
        source = Path(directory) / 'MerchantCharacterProperties.java'
        source.write_text(JAVA)
        output = subprocess.run([args.java, str(source)], check=True, text=True, capture_output=True).stdout
    names = ['letters', 'numbers', 'marks', 'formats', 'connectors', 'letterCases']
    groups = [[] for _ in names]
    for line in output.splitlines():
        kind, start, end = map(int, line.split('\t'))
        groups[kind - 1].append((start, end))
    checksum = hashlib.sha256(json.dumps(groups, separators=(',', ':')).encode()).hexdigest()
    arrays = '\n'.join('    private val ' + name + ' = intArrayOf(\n' +
        '\n'.join(f'        {start}, {end},' for start, end in group) + '\n    )'
        for name, group in zip(names, groups))
    data = '''package com.finance.tracker.business.domain

// Generated by scripts/export_local_merchant_characters.py from public Character properties.
// Temurin 21.0.6+7, Unicode 15.0; no BreakIterator rule or transition data.
// Property SHA-256: CHECKSUM
internal object MerchantCharacterData {
ARRAYS

    fun baseClass(point: Int): MerchantWordClass = when {
        contains(letters, point) -> MerchantWordClass.LETTER
        contains(numbers, point) -> MerchantWordClass.NUMBER
        contains(marks, point) -> MerchantWordClass.MARK
        contains(formats, point) -> MerchantWordClass.FORMAT
        contains(connectors, point) -> MerchantWordClass.CONNECTOR
        else -> MerchantWordClass.OTHER
    }

    fun isLetterCase(point: Int): Boolean = contains(letterCases, point)

    private fun contains(ranges: IntArray, point: Int): Boolean {
        var low = 0
        var high = ranges.size / 2 - 1
        while (low <= high) {
            val middle = (low + high) ushr 1
            when {
                point < ranges[middle * 2] -> high = middle - 1
                point > ranges[middle * 2 + 1] -> low = middle + 1
                else -> return true
            }
        }
        return false
    }
}
'''.replace('CHECKSUM', checksum).replace('ARRAYS', arrays)
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != data:
            raise RuntimeError('Frozen merchant properties differ from the public baseline')
    else:
        TARGET.write_text(data)
    print(f'{sum(map(len, groups))} property ranges; SHA-256 {checksum}')


if __name__ == '__main__':
    main()
