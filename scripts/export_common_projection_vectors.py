#!/usr/bin/env python3
"""Embed the existing projection and relation oracles for common tests without a second fixture source."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VECTORS = {
    'projection': ('python-projection-rules.json', 'CashProjectionOriginalVectors'),
    'graph': ('python-cash-relation-graphs.json', 'CashRelationGraphOriginalVectors'),
    'planning': ('python-cash-relation-planning.json', 'CashRelationPlanningOriginalVectors'),
    'platform-rows': ('python-platform-row-normalization.json', 'LocalPlatformRowOriginalVectors'),
    'bank-rows': ('python-bank-row-normalization.json', 'LocalBankRowOriginalVectors'),
    'icbc-rows': ('python-icbc-pdf-row-normalization.json', 'LocalIcbcRowOriginalVectors'),
    'source-effects': ('python-cash-source-effects.json', 'CashSourceEffectsOriginalVectors'),
}


def render(source, name):
    payload = json.dumps(json.loads(source.read_text()), ensure_ascii=False, separators=(',', ':'))
    chunks = [json.dumps(payload[i:i + 3000], ensure_ascii=True).replace('$', r'\$')
              for i in range(0, len(payload), 3000)]
    return ('package com.finance.tracker.business.domain\n\n'
            '// Generated by scripts/export_common_projection_vectors.py from the backend projection oracle.\n'
            f'internal object {name} {{\n'
            '    val json:String by lazy {listOf(\n' +
            ',\n'.join('        ' + chunk for chunk in chunks) +
            '\n    ).joinToString("")}\n}\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--kind', choices=(*VECTORS, 'all'), default='projection')
    args = parser.parse_args()
    selected = VECTORS if args.kind == 'all' else {args.kind: VECTORS[args.kind]}
    for kind, (fixture, name) in selected.items():
        source = ROOT / 'compose/backend/src/test/resources' / fixture
        target = ROOT / 'compose/business-domain/src/commonTest/kotlin/com/finance/tracker/business/domain' / f'{name}.kt'
        expected = render(source, name)
        if args.check:
            if not target.exists() or target.read_text() != expected:
                raise SystemExit(f'common {kind} vectors are stale; run scripts/export_common_projection_vectors.py --kind {kind}')
        else:
            target.write_text(expected)


if __name__ == '__main__':
    main()
