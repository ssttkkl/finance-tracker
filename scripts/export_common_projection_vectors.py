#!/usr/bin/env python3
"""Embed the existing projection and relation oracles for common tests without a second fixture source."""
import argparse
import base64
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VECTORS = {
    'funding-resolve': ('python-cash-funding.json', 'LocalFundingResolutionOriginalVectors'),
    'funding-scan': ('python-cash-funding.json', 'LocalFundingScanOriginalVectors'),
    'source-account': ('python-cash-account-mapping.json', 'LocalSourceAccountOriginalVectors'),
    'projection': ('python-projection-rules.json', 'CashProjectionOriginalVectors'),
    'graph': ('python-cash-relation-graphs.json', 'CashRelationGraphOriginalVectors'),
    'planning': ('python-cash-relation-planning.json', 'CashRelationPlanningOriginalVectors'),
    'bank-tsv-bytes': ('python-bank-statement-documents.json', 'BankTsvOriginalVectors'),
    'platform-csv-text': ('python-cash-statement-documents.json', 'PlatformCsvTextOriginalVectors'),
    'platform-rows': ('python-platform-row-normalization.json', 'LocalPlatformRowOriginalVectors'),
    'bank-rows': ('python-bank-row-normalization.json', 'LocalBankRowOriginalVectors'),
    'icbc-rows': ('python-icbc-pdf-row-normalization.json', 'LocalIcbcRowOriginalVectors'),
    'source-effects': ('python-cash-source-effects.json', 'CashSourceEffectsOriginalVectors'),
}


def render(source, name):
    values = json.loads(source.read_text())
    if name == 'LocalFundingResolutionOriginalVectors':
        values = [{**case, 'original_index': index} for index, case in enumerate(values) if case['kind'] == 'resolve']
        assert len(values) == 57
    if name == 'LocalFundingScanOriginalVectors':
        values = [{**case, 'original_index': index} for index, case in enumerate(values) if case['kind'] == 'scan']
        assert len(values) == 64
    if name == 'PlatformCsvTextOriginalVectors':
        decoded = []
        for index, case in enumerate(values):
            content = base64.b64decode(case['content'])
            # The shared text stage excludes byte-input guards and workbook/ZIP processing.
            # Their complete original cases remain in the backend's byte-level oracle.
            if not content or content.startswith(b'PK'):
                continue
            try:
                text = content.decode('utf-8')
            except UnicodeDecodeError:
                text = content.decode('gb18030')
            if text.startswith('\ufeff'):
                text = text[1:]
            decoded.append({**{key: value for key, value in case.items() if key != 'content'},
                'original_index': index, 'text': text})
        assert [case['original_index'] for case in decoded] == [*range(8), 9, 10]
        values = decoded
    if name == 'BankTsvOriginalVectors':
        selected = []
        for index, case in enumerate(values):
            content = base64.b64decode(case['content'])
            if content[:2] not in (b'\xff\xfe', b'\xfe\xff'):
                continue
            selected.append({**{key: value for key, value in case.items() if key != 'content'},
                'original_index': index, 'content_hex': content.hex()})
        assert [case['original_index'] for case in selected] == list(range(6, 11))
        values = selected
    payload = json.dumps(values, ensure_ascii=False, separators=(',', ':'))
    chunks = [json.dumps(payload[i:i + 3000], ensure_ascii=True).replace('$', r'\$')
              for i in range(0, len(payload), 3000)]
    return ('package com.finance.tracker.business.domain\n\n'
            f'// Generated by scripts/export_common_projection_vectors.py from the backend {"source-account" if name == "LocalSourceAccountOriginalVectors" else "funding" if name in ("LocalFundingScanOriginalVectors", "LocalFundingResolutionOriginalVectors") else "projection"} oracle.\n'
            f'internal object {name} {{\n'
            '    val json:String by lazy {listOf(\n' +
            ',\n'.join('        ' + chunk for chunk in chunks) +
            '\n    ).joinToString("")}\n}\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--kind', choices=(*VECTORS, 'all'), default='projection')
    args = parser.parse_args()
    selected = VECTORS if args.kind == 'all' else {args.kind: VECTORS[args.kind]}
    for kind, (fixture, name) in selected.items():
        source = ROOT / 'compose/backend/src/test/resources' / fixture
        target = ROOT / 'compose/business-domain/src/commonTest/kotlin/com/finance/tracker/business/domain' / f'{name}.kt'
        expected = render(source, name)
        if args.check:
            if not target.exists() or target.read_text() != expected:
                raise SystemExit(f'common {kind} vectors are stale; run scripts/export_common_projection_vectors.py --kind {kind}')
        else:
            target.write_text(expected)


if __name__ == '__main__':
    main()
