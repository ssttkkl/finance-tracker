#!/usr/bin/env python3
"""Embed the existing projection oracle for common tests without a second fixture source."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'compose/backend/src/test/resources/python-projection-rules.json'
TARGET = ROOT / 'compose/business-domain/src/commonTest/kotlin/com/finance/tracker/business/domain/CashProjectionOriginalVectors.kt'


def render():
    payload = json.dumps(json.loads(SOURCE.read_text()), ensure_ascii=False, separators=(',', ':'))
    chunks = [json.dumps(payload[i:i + 3000], ensure_ascii=True).replace('$', r'\$')
              for i in range(0, len(payload), 3000)]
    return ('package com.finance.tracker.business.domain\n\n'
            '// Generated by scripts/export_common_projection_vectors.py from the backend projection oracle.\n'
            'internal object CashProjectionOriginalVectors {\n'
            '    val json:String by lazy {listOf(\n' +
            ',\n'.join('        ' + chunk for chunk in chunks) +
            '\n    ).joinToString("")}\n}\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != expected:
            raise SystemExit('common projection vectors are stale; run scripts/export_common_projection_vectors.py')
    else:
        TARGET.write_text(expected)


if __name__ == '__main__':
    main()
