"""Generate Python Unicode 14 category-name and integer-input character tables."""
import argparse
import json
from pathlib import Path
import unicodedata


ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "compose/business-domain/src/commonMain/kotlin/com/finance/tracker/business/domain/PythonCaseFoldData.kt"
BRIDGE = ROOT / "compose/backend/src/main/kotlin/com/finance/tracker/backend/PythonCaseFoldData.kt"
VECTORS = ROOT / "compose/business-domain/src/commonTest/kotlin/com/finance/tracker/business/domain/PythonCaseTextOriginalVectors.kt"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if unicodedata.unidata_version != "14.0.0":
        raise RuntimeError("Use the project's Python 3.11 Unicode 14 oracle")
    entries = [f"{code} to {json.dumps(chr(code).casefold(), ensure_ascii=True)}"
        for code in range(0x110000) if chr(code).casefold() != chr(code)]
    uppercase = [f"{code} to {json.dumps(chr(code).upper(), ensure_ascii=True)}"
        for code in range(0x110000) if chr(code).upper() != chr(code)]
    lowercase = [f"{code} to {json.dumps(chr(code).lower(), ensure_ascii=True)}"
        for code in range(0x110000) if chr(code).lower() != chr(code)]
    def ranges(predicate):
        values, start = [], None
        for code in range(0x110001):
            matches = code < 0x110000 and predicate(chr(code))
            if matches and start is None:
                start = code
            elif not matches and start is not None:
                values.extend((start, code - 1)); start = None
        return values
    cased = ranges(lambda char: char.islower() or char.isupper() or unicodedata.category(char) == "Lt")
    ignorable = ranges(lambda char: ("AΣ" + char).lower()[1] == "ς"
        and ("AΣ" + char + "A").lower()[1] == "σ")
    content = ("package com.finance.tracker.business.domain\n\n"
        "// Generated by scripts/export_category_casefold.py using Python Unicode 14.\n"
        "internal val pythonCaseFold = mapOf(\n    " + ",\n    ".join(entries) + "\n)\n\n"
        "internal val pythonUpperCase by lazy { mapOf(\n    " + ",\n    ".join(uppercase) + "\n) }\n\n"
        "internal val pythonLowerCase by lazy { mapOf(\n    " + ",\n    ".join(lowercase) + "\n) }\n\n"
        "internal val pythonCasedRanges = intArrayOf(" + ", ".join(map(str,cased)) + ")\n"
        "internal val pythonCaseIgnorableRanges = intArrayOf(" + ", ".join(map(str,ignorable)) + ")\n"
        )
    bridge = ("package com.finance.tracker.backend\n\n"
        "// Generated by scripts/export_category_casefold.py; shared data is not exposed as mutable maps.\n"
        "internal fun pythonCaseFoldMapping(code:Int):String?=com.finance.tracker.business.domain.pythonCaseFoldMapping(code)\n"
        "internal fun pythonUpperCaseMapping(code:Int):String?=com.finance.tracker.business.domain.pythonUpperCaseMapping(code)\n"
        "internal val pythonIntegerDigitStarts = com.finance.tracker.business.domain.pythonIntegerDigitStarts\n"
        "internal val pythonNondecimalDigits = com.finance.tracker.business.domain.pythonNondecimalDigits\n")
    inputs = {chr(code) for code in range(0x110000) if any(transform(chr(code)) != chr(code)
        for transform in (str.casefold,str.upper,str.lower))}
    boundaries = {code+delta for code in cased+ignorable for delta in (-1,0,1) if 0 <= code+delta < 0x110000}
    for code in boundaries:
        char=chr(code)
        inputs.update(("AΣ"+char,"AΣ"+char+"A","A"+char+"Σ","A"+char+"ΣA"))
    inputs.update(("", "ΟΣʰ", "ΟΣʰA", "A1Σ", "AΣ‿A", "\ud800Σ", "Straße ﬃ", "𐐀𐐨"))
    rows=[[value,value.lower(),value.upper(),value.casefold()] for value in sorted(inputs)]
    payload=json.dumps(rows,ensure_ascii=True,separators=(",",":"))
    chunks=[json.dumps(payload[i:i+3000],ensure_ascii=True).replace('$',r'\$') for i in range(0,len(payload),3000)]
    vectors=("package com.finance.tracker.business.domain\n\n"
        "// Generated by scripts/export_category_casefold.py from CPython Unicode 14.\n"
        "internal object PythonCaseTextOriginalVectors {\n"
        "    val json:String by lazy {listOf(\n"+",\n".join("        "+chunk for chunk in chunks)+"\n    ).joinToString(\"\")}\n}\n")
    for target,expected in ((TARGET,content),(BRIDGE,bridge),(VECTORS,vectors)):
        if args.check:
            if not target.exists() or target.read_text() != expected:
                raise RuntimeError(f"Case-fold artifact is stale: {target.relative_to(ROOT)}")
        else:
            target.write_text(expected)
    print(f"{len(entries)} Unicode case-fold mappings {'verified' if args.check else 'generated'}")


if __name__ == "__main__":
    main()
