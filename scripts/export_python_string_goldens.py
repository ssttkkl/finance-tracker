"""Generate Unicode 14 printability and anonymous non-credential JSON text goldens."""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
import random
import struct
import unicodedata

ROOT = Path(__file__).resolve().parents[1] / "compose/backend/src"


def generated_files():
    if unicodedata.unidata_version != "14.0.0":
        raise ValueError("requires Python 3.11 Unicode 14 oracle")
    ranges = []
    start = None
    for code in range(0x110001):
        printable = code < 0x110000 and chr(code).isprintable()
        if printable and start is None:
            start = code
        if not printable and start is not None:
            ranges.extend((start, code - 1)); start = None
    letters = []
    start = None
    for code in range(0x110001):
        alpha = code < 0x110000 and chr(code).isalpha()
        if alpha and start is None:
            start = code
        if not alpha and start is not None:
            letters.extend((start, code - 1)); start = None
    production = """package com.finance.tracker.backend

// Generated by scripts/export_python_string_goldens.py; verify with --check.
internal val pythonPrintableRanges = intArrayOf(%s)
internal val pythonWhitespace = intArrayOf(%s)
internal val pythonLetterRanges = intArrayOf(%s)
""" % (", ".join(hex(code) for code in ranges), ", ".join(hex(code) for code in range(0x110000) if chr(code).isspace()), ", ".join(hex(code) for code in letters))
    inputs = ["null", "true", "false", "0", "-0", "1.0", "-0.0", "1e-6", "1e-4", "1e15", "1e16", "1e23", "5e-324", "-5e-324", "1e999", "-1e999", "99999999999999999999999999", "{}", "[]", '{"key":[true,null,1,1.0]}']
    for code in ranges + [0, 1, 9, 10, 13, 32, 39, 34, 92, 0xd800, 0xdc00, 0x1fae8]:
        inputs.append(json.dumps([chr(code)], ensure_ascii=True))
    rng = random.Random(20261028)
    for _ in range(600):
        value = struct.unpack("!d", rng.getrandbits(64).to_bytes(8, "big"))[0]
        if math.isfinite(value):
            inputs.append(json.dumps(value))
    for exponent in range(-1074, 1024):
        power = math.ldexp(1.0, exponent)
        for value in (math.nextafter(power, 0.0), power, math.nextafter(power, math.inf)):
            inputs.extend((json.dumps(value), json.dumps(-value)))
    cases = [{"json": raw, "expected": str(json.loads(raw))} for raw in inputs]
    encoded = json.dumps(cases, ensure_ascii=True, separators=(",", ":")).replace("$", "${'$'}")
    chunks = [encoded[i:i + 12000] for i in range(0, len(encoded), 12000)]
    tests = """package com.finance.tracker.backend

// Generated from Python str/json.loads by scripts/export_python_string_goldens.py.
internal val pythonStringGoldens = listOf(
%s
).joinToString("")
""" % ",\n".join('    """' + chunk + '"""' for chunk in chunks)
    return {ROOT / "main/kotlin/com/finance/tracker/backend/PythonCharacterData.kt": production,
        ROOT / "test/kotlin/com/finance/tracker/backend/PythonStringGoldenData.kt": tests}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in generated_files().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"generated content differs: {path}")
        else:
            path.write_text(content)
    print("Python text compatibility oracle verified" if args.check else "Python text compatibility oracle generated")
