data class CashRecordDraft(
    val id: String? = null,
    val originalCategoryId: String? = null,
    val occurredAt: String = "",
    val amount: String = "",
    val currency: String = "CNY",
    val counterparty: String = "",
    val counterpartyAccount: String = "",
    val note: String = "",
    val accountName: String = "",
    val recordType: String = "",
    val recordSubtype: String = "not_applicable",
    val categoryId: String? = null,
    val projectionVersion: Long? = null,
) {
    fun toWrite(confirmRelationImpact: Boolean): CashRecordWrite = CashRecordWrite(
        occurredAt = occurredAt,
        amount = amount,
        currency = currency,
        counterparty = counterparty,
        counterpartyAccount = counterpartyAccount,
        note = note,
        accountName = accountName,
        recordType = recordType,
        recordSubtype = recordSubtype,
        categoryId = categoryId,
        projectionVersion = projectionVersion.takeIf { id != null && categoryId != originalCategoryId },
        confirmRelationImpact = true.takeIf { confirmRelationImpact },
    )
}
